"""Agent boundaries: deterministic retrieval, generator-backed proposal, rule critic.

The critic is a deliberately conservative **deterministic verifier**, not an
LLM critic or proof of natural-language groundedness. It checks only known,
auditable constraints, source references, and high-precision string policies.
"""

from collections.abc import Sequence
import json
import re
from typing import Protocol

from recsys.multiagent.source_guard import TypedSourceGuard

from pydantic import ValidationError

from recsys.baseline.contracts import SingleAgentAnswer
from recsys.baseline.pipeline import SYSTEM_INSTRUCTIONS, build_context
from recsys.multiagent.contracts import CriticIssue, CriticVerdict
from recsys.retrieval.retriever import CatalogRetriever
from recsys.schemas import RetrievalResult, UserPreferences


class Generator(Protocol):
    def generate(self, instructions: str, context: str) -> str: ...


class PreferenceRetrievalAgent:
    """Stage 3.0 expects validated structured preferences, not free-text parsing."""

    def __init__(self, retriever: CatalogRetriever):
        self.retriever = retriever

    def run(self, preferences: UserPreferences, *, top_k: int = 3) -> RetrievalResult:
        return self.retriever.retrieve(preferences, top_k=top_k)


class RecommendationAgent:
    """One generation per call, reusing the Single-Agent baseline context contract."""

    def __init__(self, generator: Generator):
        self.generator = generator

    def propose(self, retrieval: RetrievalResult, *, feedback: CriticVerdict | None = None) -> str:
        instructions = SYSTEM_INSTRUCTIONS
        if feedback is not None:
            if feedback.approved or not feedback.issues:
                raise ValueError("revision feedback must describe rejected proposal issues")
            # Feedback is generated by the deterministic critic, never directly
            # from untrusted model text; bounded in size, without prior raw answer.
            structured_feedback = [
                {"code": issue.code, "product_id": issue.product_id}
                for issue in feedback.issues[:10]
            ]
            instructions += (
                "\nREVISION: The previous structured answer failed checks. "
                "Generate a fresh JSON answer using only the same retrieved evidence. "
                "Do not assume an unsupported claim is true. "
                "Failure codes: " + json.dumps(structured_feedback, separators=(",", ":"))
                + "\nNo additional candidate products or evidence are available."
            )
        return self.generator.generate(instructions, build_context(retrieval))


class CriticVerificationAgent:
    """Defensive checks for eligibility, cited fields, and selected prohibited claims.

    Defaults require a cited field reference for every explicitly required
    attribute in an accepted recommendation. Such a reference is **not**
    independent factual corroboration or a claim-level entailment judgment.
    """

    PROHIBITED_PHRASES: tuple[str, ...] = (
        "clinically proven",
        "cure eczema",
        "cures eczema",
        "guaranteed cure",
        "fda approved",
    )

    def __init__(self, *, require_attribute_citations: bool = True,
                 source_guard: TypedSourceGuard | None = None):
        self.require_attribute_citations = require_attribute_citations
        self.source_guard = source_guard

    def review(
        self,
        answer: SingleAgentAnswer | None,
        preferences: UserPreferences,
        retrieval: RetrievalResult,
        *,
        invalid_generation: bool = False,
    ) -> CriticVerdict:
        issues: list[CriticIssue] = []
        if invalid_generation or answer is None:
            return CriticVerdict(approved=False, issues=[
                CriticIssue(code="invalid_generation", detail="Response failed the strict JSON response schema")
            ])

        if self.source_guard is not None:
            self.source_guard.bind(retrieval.catalog_sha256)
        by_id = {candidate.product.product_id: candidate for candidate in retrieval.candidates}
        for recommendation in answer.recommendations:
            product_id = recommendation.product_id
            candidate = by_id.get(product_id)
            if candidate is None:
                issues.append(CriticIssue(
                    code="product_not_retrieved", product_id=product_id,
                    detail="Recommended product is outside the retrieved candidates",
                ))
                continue

            reason = CatalogRetriever._filter_reason(candidate.product, preferences)
            if reason is not None:
                issues.append(CriticIssue(
                    code="constraint_violation", product_id=product_id,
                    detail=f"Candidate violates hard preference: {reason}",
                ))

            evidence_by_id = {e.evidence_id: e for e in candidate.evidence}
            cited = set(recommendation.evidence_ids)
            absent = cited - set(evidence_by_id)
            if absent:
                issues.append(CriticIssue(
                    code="invalid_citation", product_id=product_id,
                    detail="Citation ID does not belong to this retrieved product",
                ))

            if self.require_attribute_citations:
                referenced_fields = {
                    evidence_by_id[eid].supported_field
                    for eid in cited if eid in evidence_by_id
                }
                for attribute in sorted(preferences.required_attributes):
                    if f"attributes.{attribute}" not in referenced_fields:
                        issues.append(CriticIssue(
                            code="required_attribute_uncited", product_id=product_id,
                            detail=f"Missing field citation for required attribute: {attribute}",
                        ))

            if self.source_guard is not None:
                for finding in self.source_guard.evaluate(
                    product_id=product_id,
                    required_attributes=preferences.required_attributes,
                    evidence_ids=cited,
                ):
                    issues.append(CriticIssue(
                        code=finding.code, product_id=product_id,
                        detail=f"{finding.field}: {finding.detail}",
                    ))

            normalized = re.sub(r"\s+", " ", recommendation.reason.casefold())
            for phrase in self.PROHIBITED_PHRASES:
                if phrase in normalized:
                    issues.append(CriticIssue(
                        code="prohibited_claim_phrase", product_id=product_id,
                        detail=f"Reason includes a prohibited claim phrase: {phrase}",
                    ))
        return CriticVerdict(approved=not issues, issues=issues)
